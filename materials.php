document.addEventListener('DOMContentLoaded', function () {

    document.querySelectorAll('.gallery-trigger').forEach(function(trigger){

        trigger.addEventListener('click', function(e){

            e.preventDefault();

            let images = JSON.parse(this.getAttribute('data-gallery'));

            let galleryHtml = '';

            images.forEach(function(img, index){

                galleryHtml += `
                    <div class="carousel-item ${index === 0 ? 'active' : ''}">
                        <img src="${img}"
                             class="d-block w-100"
                             style="max-height:700px; object-fit:contain;"
                             alt="">
                    </div>
                `;

            });

            document.getElementById('galleryImages').innerHTML = galleryHtml;

            const modal = new bootstrap.Modal(
                document.getElementById('galleryModal')
            );

            modal.show();

        });

    });

});
